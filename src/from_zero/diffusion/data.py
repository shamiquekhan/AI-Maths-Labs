"""Small grayscale image datasets with a deterministic synthetic fallback."""

from __future__ import annotations

import warnings
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import torch

from ..core.paths import resolve_path


@dataclass
class ImageData:
    train: torch.Tensor
    val: torch.Tensor
    metadata: dict[str, Any]

    @property
    def image_shape(self) -> tuple[int, int, int]:
        return tuple(self.train.shape[1:])  # type: ignore[return-value]


def load_image_dataset(
    name: str = "mnist",
    *,
    image_size: int = 28,
    max_samples: int | None = 6000,
    data_dir: str | Path = "data",
    download: bool = True,
    seed: int = 42,
) -> ImageData:
    """Load MNIST/Fashion-MNIST or generate simple synthetic shapes.

    Images are normalized to ``[-1, 1]``.  If a torchvision download is not
    available, the function falls back to deterministic synthetic shapes and
    records that choice in the metadata.
    """

    if image_size < 8 or image_size > 128:
        raise ValueError("image_size must be in [8, 128]")
    if max_samples is not None and max_samples < 16:
        raise ValueError("max_samples must be at least 16 or None")
    key = name.lower()
    if key in {"mnist", "fashion_mnist", "fashion-mnist"}:
        try:
            images, labels, source = _load_torchvision(
                key,
                image_size=image_size,
                max_samples=max_samples,
                data_dir=resolve_path(data_dir),
                download=download,
                seed=seed,
            )
        except Exception as exc:
            warnings.warn(
                f"Could not load {name} ({exc}); using synthetic shapes instead.",
                RuntimeWarning,
                stacklevel=2,
            )
            count = max_samples or 2000
            images = make_synthetic_images(count, image_size=image_size, seed=seed)
            labels = None
            source = "synthetic fallback"
    elif key in {"synthetic", "shapes"}:
        count = max_samples or 2000
        images = make_synthetic_images(count, image_size=image_size, seed=seed)
        labels = None
        source = "synthetic shapes generated by from_zero"
    else:
        raise ValueError(
            f"Unknown image dataset {name!r}; choose mnist, fashion_mnist, or synthetic"
        )

    n_val = max(1, round(0.1 * len(images)))
    train = images[:-n_val].contiguous()
    val = images[-n_val:].contiguous()
    metadata = {
        "dataset": name,
        "source": source,
        "image_size": image_size,
        "channels": 1,
        "n_train": len(train),
        "n_val": len(val),
        "normalization": "[-1, 1]",
        "license_note": _license_note(key),
        "labels_used": labels is not None,
    }
    return ImageData(train=train, val=val, metadata=metadata)


def make_synthetic_images(
    count: int,
    *,
    image_size: int = 28,
    seed: int = 42,
) -> torch.Tensor:
    """Generate deterministic circles, squares, rings, crosses, and strokes."""

    if count < 1:
        raise ValueError("count must be positive")
    if image_size < 8:
        raise ValueError("image_size must be at least 8")
    rng = np.random.default_rng(seed)
    images = np.zeros((count, 1, image_size, image_size), dtype=np.float32)
    yy, xx = np.mgrid[0:image_size, 0:image_size]
    for index in range(count):
        canvas = np.zeros((image_size, image_size), dtype=np.float32)
        shape = int(rng.integers(0, 5))
        center_x = float(rng.uniform(0.32, 0.68) * image_size)
        center_y = float(rng.uniform(0.32, 0.68) * image_size)
        radius = float(rng.uniform(0.14, 0.28) * image_size)
        if shape == 0:
            mask = (xx - center_x) ** 2 + (yy - center_y) ** 2 <= radius**2
        elif shape == 1:
            half = radius
            mask = (np.abs(xx - center_x) <= half) & (np.abs(yy - center_y) <= half)
        elif shape == 2:
            distance = (xx - center_x) ** 2 + (yy - center_y) ** 2
            mask = (distance <= radius**2) & (distance >= (0.55 * radius) ** 2)
        elif shape == 3:
            thickness = max(1.0, radius * 0.28)
            horizontal = (np.abs(yy - center_y) <= thickness) & (np.abs(xx - center_x) <= radius)
            vertical = (np.abs(xx - center_x) <= thickness) & (np.abs(yy - center_y) <= radius)
            mask = horizontal | vertical
        else:
            slope = float(rng.uniform(-1.0, 1.0))
            thickness = max(1.0, radius * 0.22)
            mask = (np.abs((yy - center_y) - slope * (xx - center_x)) <= thickness) & (
                np.abs(xx - center_x) <= radius
            )
        canvas[mask] = float(rng.uniform(0.65, 1.0))
        canvas += rng.normal(0.0, 0.025, size=canvas.shape).astype(np.float32)
        images[index, 0] = np.clip(canvas * 2.0 - 1.0, -1.0, 1.0)
    return torch.from_numpy(images)


def _load_torchvision(
    name: str,
    *,
    image_size: int,
    max_samples: int | None,
    data_dir: Path,
    download: bool,
    seed: int,
) -> tuple[torch.Tensor, torch.Tensor | None, str]:
    from torchvision import datasets, transforms

    data_dir.mkdir(parents=True, exist_ok=True)
    operations: list[Any] = []
    if image_size != 28:
        operations.append(transforms.Resize(image_size))
    operations.extend(
        [
            transforms.ToTensor(),
            transforms.Lambda(lambda image: image * 2.0 - 1.0),
        ]
    )
    transform = transforms.Compose(operations)
    if name == "mnist":
        dataset = datasets.MNIST(
            root=str(data_dir), train=True, download=download, transform=transform
        )
        source = "MNIST via torchvision"
    else:
        dataset = datasets.FashionMNIST(
            root=str(data_dir), train=True, download=download, transform=transform
        )
        source = "Fashion-MNIST via torchvision"
    indices = torch.randperm(len(dataset), generator=torch.Generator().manual_seed(seed))
    if max_samples is not None:
        indices = indices[:max_samples]
    images = torch.stack([dataset[int(index)][0] for index in indices])
    labels = torch.tensor([int(dataset[int(index)][1]) for index in indices], dtype=torch.long)
    return images, labels, source


def _license_note(name: str) -> str:
    if name == "mnist":
        return "MNIST is distributed by its original authors; check the current terms before redistribution."
    if name in {"fashion_mnist", "fashion-mnist"}:
        return "Fashion-MNIST is released under the MIT license by Zalando Research."
    return "Synthetic images generated locally; no external data license applies."
